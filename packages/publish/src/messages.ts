/** The built-in catalogues. Other languages start from English; a site adds its words with `messages`. */
export const MESSAGES: Record<string, Messages> = { en, ru };

const base = (locale: string) => locale.toLowerCase().split("-")[0]!;

/** The words for one language: built-in, then the site's own. */
export function messagesFor(config: Pick<Config, "messages">, locale: string): Messages {
  return { ...(MESSAGES[base(locale)] ?? en), ...(config.messages[locale] ?? {}) };
}

/** A message with its placeholders filled in. An unknown key shows as itself, so a gap is visible, not silent. */
export function format(m: Messages, key: string, vars: Record<string, string | number> = {}): string {
  const text = m[key] ?? key;
  return text.replace(/\{(\w+)\}/g, (all, name: string) => (name in vars ? String(vars[name]) : all));
}

/** A plural message: key.one, key.few, key.many or key.other, as the language's rules choose for n. */
export function plural(m: Messages, key: string, n: number, vars: Record<string, string | number> = {}): string {
  const rule = new Intl.PluralRules(m.intl ?? "en-GB").select(n);
  const k = m[`${key}.${rule}`] !== undefined ? `${key}.${rule}` : `${key}.other`;
  return format(m, k, { n, ...vars });
}

/** Words in the reader's language, with helpers for everything that is formatted. */
export interface Words {
  locale: string;
  m: Messages;
  t: (key: MessageKey | (string & {}), vars?: Record<string, string | number>) => string;
  n: (key: string, count: number, vars?: Record<string, string | number>) => string;
  /** Quote marks around someone's words in this language. */
  q: (text: string) => string;
}

export function words(config: Pick<Config, "messages">, locale: string): Words {
  const m = messagesFor(config, locale);
  return {
    locale,
    m,
    t: (key, vars) => format(m, key, vars),
    n: (key, count, vars) => plural(m, key, count, vars),
    q: (text) => `${m["quote.open"]}${text}${m["quote.close"]}`,
  };
}
