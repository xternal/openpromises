// Writes src/entities.ts, every HTML5 named character reference, from the WHATWG list: pnpm --filter @openpromises/quotes entities.
// With a path (node scripts/entities.mjs entities.json), it reads a saved copy of the list instead of fetching it.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const URL = "https://html.spec.whatwg.org/entities.json";
const from = process.argv[2];
const list = JSON.parse(from ? readFileSync(from, "utf8") : await (await fetch(URL)).text());

// Invisible, spacing and combining characters are written as escapes, so the table can be read; the rest as themselves.
const escape = (s) =>
  [...s]
    .map((c) => {
      const code = c.codePointAt(0);
      if (c === '"' || c === "\\") return `\\${c}`;
      if (/[\p{C}\p{Z}\p{M}]/u.test(c)) return code > 0xffff ? `\\u{${code.toString(16)}}` : `\\u${code.toString(16).padStart(4, "0")}`;
      return c;
    })
    .join("");

const byName = (a, b) => (a < b ? -1 : a > b ? 1 : 0);
const names = Object.keys(list)
  .filter((k) => k.endsWith(";"))
  .map((k) => k.slice(1, -1))
  .sort(byName);
// The old names a browser also reads without their semicolon ("&eacute"); each stands for the same characters as with it.
const legacy = Object.keys(list)
  .filter((k) => !k.endsWith(";"))
  .map((k) => k.slice(1))
  .sort(byName);
for (const name of legacy) if (list[`&${name}`].characters !== list[`&${name};`]?.characters) throw new Error(`&${name} differs from &${name};`);

const lines = names.map((name) => `  ${name}: "${escape(list[`&${name};`].characters)}",`);
const wrapped = [];
for (const name of legacy.map((n) => `"${n}"`)) {
  const last = wrapped.at(-1);
  if (last !== undefined && last.length + name.length + 2 <= 120) wrapped[wrapped.length - 1] = `${last}, ${name}`;
  else wrapped.push(`  ${name}`);
}
writeFileSync(
  join(import.meta.dirname, "..", "src", "entities.ts"),
  `// Generated by scripts/entities.mjs from ${URL}: do not edit by hand.

/** Every HTML5 named character reference, by its case-sensitive name without "&" and ";" (${names.length}). */
export const ENTITIES: Readonly<Record<string, string>> = {
${lines.join("\n")}
};

/** The names a browser also reads without their semicolon, as in "&eacute" (${legacy.length}). */
export const LEGACY: ReadonlySet<string> = new Set([
${wrapped.join(",\n")},
]);

/** The longest of them, in letters. */
export const LONGEST_LEGACY = ${Math.max(...legacy.map((n) => n.length))};
`,
);
console.log(`wrote src/entities.ts (${names.length} names, ${legacy.length} also without a semicolon)`);
